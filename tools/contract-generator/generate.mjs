import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import openapiTS, { astToString } from 'openapi-typescript';
import SwaggerParser from '@apidevtools/swagger-parser';
import { z } from 'zod';

const root = fileURLToPath(new URL('../../', import.meta.url));
const require = createRequire(import.meta.url);
export async function generateContracts({ check = false } = {}) {
  const { createApp } = require(resolve(root, 'apps/api/dist/app.js'));
  const { createOpenApiDocument } = require(
    resolve(root, 'apps/api/dist/openapi.js'),
  );
  const {
    AgentCommandSchema,
    AgentResultSchema,
  } = require('@cloudlane/contracts/agent');
  const app = await createApp({ documentation: false });
  try {
    await app.init();
    const document = createOpenApiDocument(app);
    await SwaggerParser.validate(structuredClone(document));
    const types = astToString(await openapiTS(document, { alphabetize: true }));
    const stable = (value) =>
      Array.isArray(value)
        ? value.map(stable)
        : value && typeof value === 'object'
          ? Object.fromEntries(
              Object.entries(value)
                .sort(([a], [b]) => a.localeCompare(b, 'en'))
                .map(([key, item]) => [key, stable(item)]),
            )
          : value;
    const json = (value) => JSON.stringify(stable(value), null, 2) + '\n';
    const files = new Map([
      ['packages/contracts/openapi/cloudlane.v1.json', json(document)],
      [
        'packages/contracts/src/generated/http.ts',
        '// Generated by npm run contracts:generate. Do not edit.\n' + types,
      ],
      [
        'packages/contracts/schema/agent-command.v1.json',
        json(z.toJSONSchema(AgentCommandSchema)),
      ],
      [
        'packages/contracts/schema/agent-result.v1.json',
        json(z.toJSONSchema(AgentResultSchema)),
      ],
    ]);
    for (const [name, content] of files) {
      const path = resolve(root, name);
      if (check) {
        let actual = '';
        try {
          actual = readFileSync(path, 'utf8');
        } catch {
          /* Missing output fails below. */
        }
        if (actual !== content)
          throw new Error(
            `Generated contract drift: ${name}. Run npm run contracts:generate.`,
          );
      } else {
        mkdirSync(resolve(path, '..'), { recursive: true });
        writeFileSync(path, content);
      }
    }
    console.log(
      `PASS: ${check ? 'checked' : 'generated'} OpenAPI, client types and agent schemas (${Object.keys(document.paths).length} HTTP paths)`,
    );
    return document;
  } finally {
    await app.close();
  }
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await generateContracts({ check: process.argv.includes('--check') });
}
